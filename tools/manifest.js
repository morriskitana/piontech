"use strict";
/**
 * Replacement manifest: every placeholder asset -> the topic its photo must depict.
 *
 * `strong` tokens must appear in the photo TITLE for a candidate to be accepted.
 * `weak` tokens raise the score. `queries` are the search strings sent to Openverse +
 * Wikimedia Commons - keep them SHORT (1-2 words): both search back-ends AND every
 * term, so a long phrase returns nothing at all.
 *
 * Target pixel dimensions are read from tools/image-analysis.tsv so every replacement is
 * rendered at exactly the original size.
 *
 * The optional 5th tuple element restricts which sources may serve that topic:
 *   PEOPLE  modern stock photography only - Wikimedia Commons is excluded because its
 *           portrait catalogue is dominated by 19th-century studio photographs.
 *   TECH    technical subjects - Commons is allowed, it has genuine high-resolution
 *           infrastructure photography.
 */

// Modern stock photography - safe for people, offices and lifestyle.
// StockSnap first: its titles are clean and descriptive ("Team Meeting", "Businessman
// Thinking"), which is what the title-scoped scorer needs. Flickr is the fallback but
// contributes a lot of documentary noise, so it scores lower.
const PEOPLE = ["stocksnap", "wordpress", "flickr"];
// Technical subjects - Commons holds the best infrastructure photography.
const TECH = ["wikimedia", "stocksnap", "flickr", "rawpixel", "wordpress"];

// Words in a topic's `strong` list that make it a people / workplace subject.
const PEOPLE_HINTS = new Set([
  "portrait", "face", "man", "woman", "person", "people", "professional",
  "businessman", "businesswoman", "headshot", "colleagues", "staff", "workplace",
  "meeting", "handshake", "partnership", "consultant", "worker", "smile", "suit",
  "corporate", "client", "customer", "boardroom", "discussion", "collaboration",
  "team", "office",
]);

// Overrides where the automatic hint would pick the wrong source class.
const SOURCE_OVERRIDE = {
  "portfolio/portfolio_details_image_1.webp": TECH,
  "about/about_image_9.webp": TECH,
};

// Prefix overrides. The per-service detail photos and the CTA background are
// infrastructure / workplace subjects: they must be allowed to come from
// Wikimedia Commons, which holds the only genuinely high-resolution photography
// of data centres, substations and structured cabling. The automatic PEOPLE
// heuristic would otherwise exclude Commons because some of the strong tokens
// ("engineer", "team", "office") look like people topics.
const PREFIX_OVERRIDE = [
  ["services/service_details_", TECH],
  ["backgrounds/bg_image_1", TECH],
];

/** Which sources may serve this topic. */
function sourcesFor(target, strong) {
  if (SOURCE_OVERRIDE[target]) return SOURCE_OVERRIDE[target];
  for (const [prefix, sources] of PREFIX_OVERRIDE) {
    if (target.startsWith(prefix)) return sources;
  }
  for (const phrase of strong || []) {
    for (const tok of String(phrase).toLowerCase().split(/[\s-]+/)) {
      if (PEOPLE_HINTS.has(tok)) return PEOPLE;
    }
  }
  return TECH;
}

